"""Миграции: применение, откат, повторное применение и совпадение с моделями."""
import pytest
from alembic import command
from sqlalchemy import text

from tests.conftest import make_alembic_config

pytestmark = pytest.mark.db


def _public_tables(db) -> set[str]:
    async def go(s):
        rows = await s.execute(text(
            "SELECT table_name FROM information_schema.tables WHERE table_schema = 'public'"
        ))
        return {r[0] for r in rows}
    return db.run(go)


def test_head_creates_all_tables(db):
    from app.models import Base

    expected = {t.name for t in Base.metadata.sorted_tables}
    assert expected <= _public_tables(db)


def test_downgrade_base_and_upgrade_again(db_url, db):
    cfg = make_alembic_config(db_url)
    command.downgrade(cfg, "base")
    assert _public_tables(db) <= {"alembic_version"}
    command.upgrade(cfg, "head")
    from app.models import Base
    assert {t.name for t in Base.metadata.sorted_tables} <= _public_tables(db)


def test_models_match_migration(db_url):
    # Бросает AutogenerateDiffsDetected, если модели разошлись с миграциями
    command.check(make_alembic_config(db_url))
